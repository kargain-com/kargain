export type DetailStringKey = keyof (typeof DICT)["en"];

export function getDetailStrings(locale: DetailLocale) {
  return DICT[locale] ?? DICT.en;
}

export function pickDetailLocale(acceptLanguage: string | null): DetailLocale {
  if (!acceptLanguage) return "en";
  if (acceptLanguage.toLowerCase().startsWith("fr")) return "fr";
  return "en";
}
